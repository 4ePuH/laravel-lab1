<?php

declare(strict_types=1);

return [
    /*
    |--------------------------------------------------------------------------
    | Секрет для подписи токенов (HMAC-SHA256)
    |--------------------------------------------------------------------------
    | По умолчанию используем ключ приложения (APP_KEY). Это сильный
    | случайный секрет, который уже есть в каждом Laravel-проекте.
    */
    'secret' => env('TOKEN_SECRET', env('APP_KEY')),

    /*
    |--------------------------------------------------------------------------
    | Время жизни токенов (в минутах)
    |--------------------------------------------------------------------------
    | access  — короткоживущий токен доступа.
    | refresh — долгоживущий токен обновления (по умолчанию 7 дней).
    */
    'access_ttl' => (int) env('ACCESS_TOKEN_TTL', 60),
    'refresh_ttl' => (int) env('REFRESH_TOKEN_TTL', 10080),

    /*
    |--------------------------------------------------------------------------
    | Лимит одновременно активных токенов доступа на одного пользователя
    |--------------------------------------------------------------------------
    | При превышении самая старая пара токенов отзывается.
    */
    'max_active' => (int) env('MAX_ACTIVE_TOKENS', 5),
];
